#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_legacy_geometry_matches_twitch_assets() {
        assert_eq!(twitch_base_dimensions("25"), (25, 28));
        assert_eq!(twitch_high_tier_density("25"), 3.0);
        assert_eq!(twitch_base_dimensions("26"), (20, 27));
        assert_eq!(twitch_base_dimensions("18"), (20, 27));
        assert_eq!(twitch_base_dimensions("1901"), (24, 28));
    }

    #[test]
    fn modern_emotes_use_the_standard_geometry() {
        assert_eq!(twitch_base_dimensions("emotesv2_modern"), (28, 28));
        assert_eq!(twitch_high_tier_density("emotesv2_modern"), 4.0);
    }

    #[test]
    fn legacy_heart_density_keeps_its_non_integer_exception() {
        assert_eq!(twitch_high_tier_density("9"), 14.0 / 3.0);
        assert_eq!(twitch_high_tier_density("555555584"), 14.0 / 3.0);
    }
}

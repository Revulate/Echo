//! `scale` 1.0, 2.0 and 3.0, by reading each PNG's header size, and can be
//! re-measured the same way. The base size is the 1.0 image; the high-tier
//! density is the 3.0 width divided by the 1.0 width. Only ids that differ from
//! 28x28 and density 4 are listed. Every measured 2.0 image is exactly twice its
//! 1.0 size. `86` returns HTTP 404 at every scale, so its entries could not be
//! measured.

